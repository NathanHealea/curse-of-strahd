#!/usr/bin/env python3
"""Rebuild README.md (campaign home) and each folder's _index.md from note frontmatter.
Run from the campaign root:  python3 .claude/scripts/build_index.py
Generated files are overwritten — don't hand-edit them."""
import os, re, glob, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)
FOLDERS = {
    '00-evangelina-penitentia': 'Evangelina Penitentia',
    '01-sessions': 'Sessions', '02-characters/party': 'Party', '02-characters/npc': 'NPCs',
    '03-key-events': 'Key Events', '04-places': 'Places', '05-quests': 'Quests',
    '06-factions': 'Factions', '07-lore': 'Lore', '08-items': 'Items'}
SKIP = {'_index.md', 'README.md'}

def parse(path):
    t = open(path, encoding='utf-8').read()
    fm = {}
    m = re.match(r'---\n(.*?)\n---\n', t, re.S)
    body = t[m.end():] if m else t
    if m:
        for line in m.group(1).splitlines():
            line = re.sub(r'\s+#.*$', '', line)
            if ':' not in line: continue
            k, v = line.split(':', 1); v = v.strip()
            if v.startswith('['):
                v = [x.strip().strip('"') for x in v.strip('[]').split(',') if x.strip()]
            fm[k.strip()] = v
    tm = re.search(r'^# (.+)$', body, re.M)
    fm['title'] = tm.group(1).strip() if tm else os.path.basename(path)[:-3]
    fm['name'] = os.path.basename(path)[:-3]
    fm['path'] = path; fm['body'] = body
    return fm

def notes(folder):
    return sorted((parse(p) for p in glob.glob(f'{folder}/*.md') if os.path.basename(p) not in SKIP),
                  key=lambda n: n['title'].lower())

def link(n): return f"[[{n['name']}|{n['title']}]]"
NAMES = {os.path.basename(p)[:-3] for p in glob.glob('**/*.md', recursive=True)}
def ref(v): return f'[[{v}]]' if v in NAMES else (v or '').replace('-', ' ')
def sess(n):
    s = n.get('sessions') or []
    return ', '.join(f'S{x}' for x in s) if isinstance(s, list) else str(s)

def table(rows, cols):
    out = ['| ' + ' | '.join(c for c, _ in cols) + ' |', '|' + '---|' * len(cols)]
    for r in rows: out.append('| ' + ' | '.join(str(f(r)).replace('|', '\\|') for _, f in cols) + ' |')
    return '\n'.join(out)

def open_threads(n):
    m = re.search(r'^## Open (?:Questions|Threads)\s*\n(.*?)(?=^## |\Z)', n['body'], re.M | re.S)
    if not m: return []
    return [l.strip()[2:] for l in m.group(1).splitlines() if l.strip().startswith('- ') and len(l.strip()) > 2]

GEN = f"<!-- Generated by .claude/scripts/build_index.py on {datetime.date.today()} — do not edit by hand -->\n"

# ---------- folder indexes ----------
COLS = {
 '02-characters/npc': [('NPC', link), ('Disposition', lambda n: n.get('disposition', '')), ('Status', lambda n: n.get('status', '')),
                       ('Location', lambda n: ref(n.get('location'))), ('Faction', lambda n: ref(n.get('faction'))), ('Sessions', sess)],
 '02-characters/party': [('Character', link), ('Also known as', lambda n: ', '.join(a for a in n.get('aliases', [])[1:])), ('Sessions', sess)],
 '03-key-events': [('Event', link), ('Session', lambda n: n.get('session', '')), ('Location', lambda n: ref(n.get('location')))],
 '04-places': [('Place', link), ('Status', lambda n: n.get('status', '')), ('Region', lambda n: n.get('region', '')), ('Sessions', sess)],
 '05-quests': [('Quest', link), ('Status', lambda n: n.get('status', '') + (' 🤫' if n.get('secret') == 'true' else '')),
               ('Giver', lambda n: ref(n.get('giver'))), ('Location', lambda n: ref(n.get('location'))), ('Sessions', sess)],
 '06-factions': [('Faction', link), ('Disposition', lambda n: n.get('disposition', '')), ('Sessions', sess)],
 '07-lore': [('Topic', link), ('Sessions', sess)],
 '08-items': [('Item', link), ('Holder', lambda n: ref(n.get('holder'))), ('Found at', lambda n: ref(n.get('location'))), ('Sessions', sess)],
 '01-sessions': [('Session', link), ('Date', lambda n: n.get('date') or '—')],
 '00-evangelina-penitentia': [('Document', link), ('Kind', lambda n: n.get('kind', 'hub')), ('Spoilers', lambda n: '⚠️ DM-only' if n.get('spoilers') == 'true' else '')],
}
ALL = {}
for folder, label in FOLDERS.items():
    ns = notes(folder)
    if folder == '01-sessions': ns.sort(key=lambda n: int(n.get('session', 0) or 0))
    ALL[folder] = ns
    body = f"# {label} — Index\n\n{GEN}\n{len(ns)} notes. ← [[README|Campaign Home]]\n\n" + table(ns, COLS[folder]) + '\n'
    if folder == '05-quests': body += '\n🤫 = Evangelina doesn\'t know about this one.\n'
    open(f'{folder}/_index.md', 'w', encoding='utf-8').write(body)

# ---------- campaign home ----------
npcs, quests, places = ALL['02-characters/npc'], ALL['05-quests'], ALL['04-places']
sessions = ALL['01-sessions']
last = sessions[-1] if sessions else None
by = lambda ns, k, v: [n for n in ns if n.get(k) == v]
out = [f"# Curse of Strahd — Campaign Home\n\n{GEN}",
       "*Five strangers from [[Daggerford]] followed wolf tracks into the fog and woke in Barovia.*\n",
       f"**Latest session:** {link(last) if last else '—'} · **Sessions logged:** {len(sessions)} · "
       f"**Main character:** [[evangelina|Evangelina Penitentia]]\n",
       "## The Party\n", ' · '.join([ '[[evangelina|Evangelina]]'] + [link(n) for n in ALL['02-characters/party']]) + '\n',
       "## Active Quests\n", table([q for q in quests if q.get('status') in ('active', 'stalled')], COLS['05-quests']),
       "\n**Completed:** " + (', '.join(link(q) for q in by(quests, 'status', 'complete')) or '—') + '\n',
       "## Who's Who\n"]
for disp, lbl in [('friendly', 'Allies'), ('neutral', 'Neutral'), ('hostile', 'Enemies'), ('unknown', 'Unknown')]:
    g = by(npcs, 'disposition', disp)
    if g: out.append(f"- **{lbl}:** " + ', '.join(link(n) for n in g))
out += ["\n## Map of Known Places\n",
        "- **Visited:** " + ', '.join(link(n) for n in by(places, 'status', 'visited')),
        "- **Known, not visited:** " + ', '.join(link(n) for n in by(places, 'status', 'unvisited')) + '\n',
        "## Open Threads\n", "*Pulled automatically from every note's Open Questions / Open Threads section.*\n"]
for folder in ['05-quests', '02-characters/npc', '04-places', '06-factions', '07-lore', '08-items']:
    for n in ALL[folder]:
        th = open_threads(n)
        if th: out.append(f"**{link(n)}**\n" + '\n'.join(f'- {x}' for x in th) + '\n')
out += ["## Browse\n"] + [f"- [[{f}/_index|{l}]]" for f, l in FOLDERS.items()] + \
       ["- `_templates/` — blank note templates", "- `CLAUDE.md` — conventions and slash commands\n"]
open('README.md', 'w', encoding='utf-8').write('\n'.join(out))
print('Rebuilt README.md and', len(FOLDERS), 'folder indexes')

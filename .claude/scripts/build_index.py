#!/usr/bin/env python3
"""Rebuild the Evangelina home (README.md), the campaign home
(campaign/curse-of-strahd/README.md) and every folder's _index.md from note frontmatter.
Run from anywhere:  python3 .claude/scripts/build_index.py
Generated files are overwritten — don't hand-edit them."""
import os, re, glob, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)

CAMPAIGN = 'campaign/curse-of-strahd'
CAMPAIGN_TITLE = 'Curse of Strahd'
# Evangelina's own folders — the focus of this vault
EVA_FOLDERS = {'character': 'Character', 'journal': 'Journal', 'prayer': 'Prayers'}
# Campaign folders, relative to CAMPAIGN
CAMPAIGN_FOLDERS = {
    '01-sessions': 'Sessions', '02-characters/party': 'Party', '02-characters/npc': 'NPCs',
    '03-key-events': 'Key Events', '04-places': 'Places', '05-quests': 'Quests',
    '06-factions': 'Factions', '07-lore': 'Lore', '08-items': 'Items'}
SKIP = {'_index.md', 'README.md'}

ITEM = re.compile(r'\s*-\s+')

def unquote(s):
    return s[1:-1] if len(s) > 1 and s[0] == s[-1] and s[0] in '"\'' else s

def parse(path):
    t = open(path, encoding='utf-8').read()
    fm = {}
    m = re.match(r'---\n(.*?)\n---\n', t, re.S)
    body = t[m.end():] if m else t
    if m:
        # Accepts both inline lists (aliases: [A, B]) and the block form Obsidian's
        # Properties panel rewrites them into (aliases:\n  - A\n  - B).
        lines = m.group(1).splitlines()
        i = 0
        while i < len(lines):
            line = re.sub(r'\s+#.*$', '', lines[i]); i += 1
            if ':' not in line: continue
            k, v = line.split(':', 1); k, v = k.strip(), v.strip()
            if v.startswith('['):
                fm[k] = [unquote(x.strip()) for x in v.strip('[]').split(',') if x.strip()]
            elif v == '' and i < len(lines) and ITEM.match(lines[i]):
                items = []
                while i < len(lines) and ITEM.match(lines[i]):
                    items.append(unquote(re.sub(r'\s+#.*$', '', lines[i]).strip()[1:].strip())); i += 1
                fm[k] = items
            else:
                fm[k] = unquote(v)
    tm = re.search(r'^# (.+)$', body, re.M)
    fm['title'] = tm.group(1).strip() if tm else os.path.basename(path)[:-3]
    fm['name'] = os.path.basename(path)[:-3]
    fm['path'] = path; fm['body'] = body
    return fm

def notes(folder):
    return sorted((parse(p) for p in glob.glob(f'{folder}/*.md') if os.path.basename(p) not in SKIP),
                  key=lambda n: n['title'].lower())

def link(n): return f"[[{n['name']}|{n['title']}]]"
NAMES = {os.path.basename(p)[:-3] for p in glob.glob('**/*.md', recursive=True)}
def ref(v): return f'[[{v}]]' if v in NAMES else (v or '').replace('-', ' ')
def sess(n):
    s = n.get('sessions') or []
    return ', '.join(f'S{x}' for x in s) if isinstance(s, list) else str(s)

def table(rows, cols):
    out = ['| ' + ' | '.join(c for c, _ in cols) + ' |', '|' + '---|' * len(cols)]
    for r in rows: out.append('| ' + ' | '.join(str(f(r)).replace('|', '\\|') for _, f in cols) + ' |')
    return '\n'.join(out)

def open_threads(n):
    m = re.search(r'^## Open (?:Questions|Threads)\s*\n(.*?)(?=^## |\Z)', n['body'], re.M | re.S)
    if not m: return []
    return [l.strip()[2:] for l in m.group(1).splitlines() if l.strip().startswith('- ') and len(l.strip()) > 2]

def about_eva(n):
    return bool(re.search(r'Evangelina|\[\[eva(ngelina)?[\]|]', n['body']))

GEN = f"<!-- Generated by .claude/scripts/build_index.py on {datetime.date.today()} — do not edit by hand -->\n"
HOME = '[[README|Evangelina Penitentia]]'
CHOME = f'[[{CAMPAIGN}/README|{CAMPAIGN_TITLE}]]'

COLS = {
 '02-characters/npc': [('NPC', link), ('Disposition', lambda n: n.get('disposition', '')), ('Status', lambda n: n.get('status', '')),
                       ('Location', lambda n: ref(n.get('location'))), ('Faction', lambda n: ref(n.get('faction'))), ('Sessions', sess)],
 '02-characters/party': [('Character', link), ('Also known as', lambda n: ', '.join(a for a in n.get('aliases', [])[1:])), ('Sessions', sess)],
 '03-key-events': [('Event', link), ('Session', lambda n: n.get('session', '')), ('Location', lambda n: ref(n.get('location')))],
 '04-places': [('Place', link), ('Status', lambda n: n.get('status', '')), ('Region', lambda n: n.get('region', '')), ('Sessions', sess)],
 '05-quests': [('Quest', link), ('Status', lambda n: n.get('status', '') + (' 🤫' if n.get('secret') == 'true' else '')),
               ('Giver', lambda n: ref(n.get('giver'))), ('Location', lambda n: ref(n.get('location'))), ('Sessions', sess)],
 '06-factions': [('Faction', link), ('Disposition', lambda n: n.get('disposition', '')), ('Sessions', sess)],
 '07-lore': [('Topic', link), ('Sessions', sess)],
 '08-items': [('Item', link), ('Holder', lambda n: ref(n.get('holder'))), ('Found at', lambda n: ref(n.get('location'))), ('Sessions', sess)],
 '01-sessions': [('Session', link), ('Date', lambda n: n.get('date') or '—')],
 'character': [('Document', link), ('Kind', lambda n: n.get('kind', '')), ('Spoilers', lambda n: '⚠️ DM-only' if n.get('spoilers') == 'true' else '')],
 'journal': [('Entry', link), ('Session', lambda n: n.get('session', '')), ('Date', lambda n: n.get('date') or '—')],
 'prayer': [('Prayer', link), ('Occasion', lambda n: n.get('occasion', '')), ('Sessions', sess)],
}

# ---------- live Dataview tables for every _index.md ----------
# Each index renders a Dataview table of the notes in its own folder (with tags),
# so it stays current without re-running this script.
TITLE = 'default(aliases[0], file.name)'
def T(h): return f'link(file.path, {TITLE}) AS "{h}"'
def L(k, h): return f'choice({k}, link({k}), "") AS "{h}"'
S = 'sessions AS "Sessions"'
DV = {
 '02-characters/npc': [T('NPC'), 'disposition AS "Disposition"', 'status AS "Status"', L('location', 'Location'), L('faction', 'Faction'), S],
 '02-characters/party': [T('Character'), 'aliases AS "Also known as"', S],
 '03-key-events': ([T('Event'), 'session AS "Session"', L('location', 'Location')], 'session ASC'),
 '04-places': [T('Place'), 'status AS "Status"', 'region AS "Region"', S],
 '05-quests': [T('Quest'), 'choice(secret, status + " 🤫", status) AS "Status"', L('giver', 'Giver'), L('location', 'Location'), S],
 '06-factions': [T('Faction'), 'disposition AS "Disposition"', S],
 '07-lore': [T('Topic'), S],
 '08-items': [T('Item'), L('holder', 'Holder'), L('location', 'Found at'), S],
 '01-sessions': (['link(file.path, "Session " + session) AS "Session"', 'date AS "Date"'], 'session ASC'),
 'character': [T('Document'), 'kind AS "Kind"', 'choice(spoilers, "⚠️ DM-only", "") AS "Spoilers"'],
 'journal': ([T('Entry'), 'session AS "Session"', 'date AS "Date"'], 'session ASC'),
 'prayer': [T('Prayer'), 'occasion AS "Occasion"', S],
}
def dv(folder):
    spec = DV[folder]
    cols, sort = spec if isinstance(spec, tuple) else (spec, f'{TITLE} ASC')
    cols = cols + ['file.etags AS "Tags"']
    return ('```dataview\nTABLE WITHOUT ID\n  ' + ',\n  '.join(cols) +
            '\nWHERE file.folder = this.file.folder AND file.name != this.file.name'
            f'\nSORT {sort}\n```')
FM = '---\ntype: index\ntags: [index]\n---\n'

# ---------- Evangelina's folder indexes ----------
EVA = {}
for folder, label in EVA_FOLDERS.items():
    os.makedirs(folder, exist_ok=True)
    ns = notes(folder)
    if folder == 'journal': ns.sort(key=lambda n: int(n.get('session', 0) or 0))
    EVA[folder] = ns
    body = f"{FM}# {label} — Index\n\n{GEN}\n← {HOME}\n\n" + dv(folder) + '\n'
    open(f'{folder}/_index.md', 'w', encoding='utf-8').write(body)

# ---------- campaign folder indexes ----------
ALL = {}
for folder, label in CAMPAIGN_FOLDERS.items():
    ns = notes(f'{CAMPAIGN}/{folder}')
    if folder == '01-sessions': ns.sort(key=lambda n: int(n.get('session', 0) or 0))
    ALL[folder] = ns
    body = f"{FM}# {label} — Index\n\n{GEN}\n← {CHOME} · {HOME}\n\n" + dv(folder) + '\n'
    if folder == '05-quests': body += '\n🤫 = Evangelina doesn\'t know about this one.\n'
    open(f'{CAMPAIGN}/{folder}/_index.md', 'w', encoding='utf-8').write(body)

npcs, quests, places = ALL['02-characters/npc'], ALL['05-quests'], ALL['04-places']
sessions, events = ALL['01-sessions'], ALL['03-key-events']
last = sessions[-1] if sessions else None
by = lambda ns, k, v: [n for n in ns if n.get(k) == v]

# ---------- Evangelina home (vault README) ----------
# secret: true means Eva doesn't know about it — it never shows on her own page
eva_quests = [q for q in quests if about_eva(q) and q.get('secret') != 'true'
              and q.get('status') in ('active', 'stalled')]
eva_events = [e for e in events if about_eva(e)]
home = [f"# Evangelina Penitentia\n\n{GEN}",
        "![[evangelina-portrait.png|220]]\n",
        '*"By the Dawnfather\'s light, the dawn comes."*\n',
        "Zealous Dawnborn of [[dawnborn-of-pelor|Pelor]], raised at the Dawnspire Monastery. "
        "Paladin, Oath of Devotion · Chaotic Good. Her arc: **righteous fire vs. destructive wrath** — "
        "learning that light can illuminate without incinerating.\n",
        f"**Character page:** [[evangelina|Evangelina Penitentia]] · **Campaign:** {CHOME} · "
        f"**Latest session:** {link(last) if last else '—'}\n",
        "## Her Pages\n", table(EVA['character'], COLS['character']),
        "\n## Journal\n",
        (table(EVA['journal'], COLS['journal']) if EVA['journal']
         else "*No entries yet — write one with `/journal`.*"),
        "\n## Prayers\n",
        (' · '.join(link(n) for n in EVA['prayer']) if EVA['prayer']
         else "*None written yet — write one with `/prayer`.*"),
        "\n## Where She's Been Tested\n",
        ('\n'.join(f"- {link(e)}" + (f" (S{e['session']})" if e.get('session') else '') for e in eva_events)
         or '- —'),
        "\n## What She Owes\n",
        ('\n'.join(f"- {link(q)} — {q.get('status', '')}" for q in eva_quests) or '- —'),
        "\n## Browse\n"]
home += [f"- [[{f}/_index|{l}]]" for f, l in EVA_FOLDERS.items()]
home += [f"- [[{CAMPAIGN}/README|{CAMPAIGN_TITLE} — the campaign archive]]",
         "- `art/` — portrait and character sheet",
         "- `CLAUDE.md` — conventions and slash commands\n"]
open('README.md', 'w', encoding='utf-8').write('\n'.join(home))

# ---------- campaign home ----------
out = [f"---\ntype: campaign\naliases: [{CAMPAIGN_TITLE}]\ntags: [campaign, {os.path.basename(CAMPAIGN)}]\n---\n"
       f"# {CAMPAIGN_TITLE} — Campaign Home\n\n{GEN}",
       "*Five strangers from [[Daggerford]] followed wolf tracks into the fog and woke in Barovia.*\n",
       f"**Latest session:** {link(last) if last else '—'} · **Sessions logged:** {len(sessions)} · "
       f"**Main character:** {HOME}\n",
       "## The Party\n", ' · '.join(['[[evangelina|Evangelina]]'] + [link(n) for n in ALL['02-characters/party']]) + '\n',
       "## Active Quests\n", table([q for q in quests if q.get('status') in ('active', 'stalled')], COLS['05-quests']),
       "\n**Completed:** " + (', '.join(link(q) for q in by(quests, 'status', 'complete')) or '—') + '\n',
       "## Who's Who\n"]
for disp, lbl in [('friendly', 'Allies'), ('neutral', 'Neutral'), ('hostile', 'Enemies'), ('unknown', 'Unknown')]:
    g = by(npcs, 'disposition', disp)
    if g: out.append(f"- **{lbl}:** " + ', '.join(link(n) for n in g))
out += ["\n## Map of Known Places\n",
        "- **Visited:** " + ', '.join(link(n) for n in by(places, 'status', 'visited')),
        "- **Known, not visited:** " + ', '.join(link(n) for n in by(places, 'status', 'unvisited')) + '\n',
        "## Open Threads\n", "*Pulled automatically from every note's Open Questions / Open Threads section.*\n"]
for folder in ['05-quests', '02-characters/npc', '04-places', '06-factions', '07-lore', '08-items']:
    for n in ALL[folder]:
        th = open_threads(n)
        if th: out.append(f"**{link(n)}**\n" + '\n'.join(f'- {x}' for x in th) + '\n')
out += ["## Browse\n"] + [f"- [[{CAMPAIGN}/{f}/_index|{l}]]" for f, l in CAMPAIGN_FOLDERS.items()] + \
       [f"\n**Live views** (sortable, filterable — Obsidian Bases):",
        f"- [[{CAMPAIGN}/npc-roster.base|NPC Roster]] — by disposition, by location, who's still alive",
        f"- [[{CAMPAIGN}/quest-board.base|Quest Board]] — open, what Eva knows, behind her back\n",
        f"- `{CAMPAIGN}/_templates/` — blank note templates",
        f"- ← {HOME} — whose story this archive serves\n"]
open(f'{CAMPAIGN}/README.md', 'w', encoding='utf-8').write('\n'.join(out))

# ---------- campaign list ----------
def camp_title(c):
    home = f'{c}/README.md'
    if os.path.exists(home):
        m = re.search(r'^# (.+?)(?: — Campaign Home)?$', open(home, encoding='utf-8').read(), re.M)
        if m: return m.group(1).strip()
    return os.path.basename(c).replace('-', ' ').title()

camps = sorted(d.replace('\\', '/') for d in glob.glob('campaign/*') if os.path.isdir(d))
open('campaign/_index.md', 'w', encoding='utf-8').write(
    f"{FM}# Campaigns — Index\n\n{GEN}\n← {HOME}\n\n"
    '```dataview\nTABLE WITHOUT ID\n  link(file.path, default(aliases[0], file.folder)) AS "Campaign",\n'
    '  file.etags AS "Tags"\nWHERE type = "campaign"\nSORT file.folder ASC\n```\n')

print('Rebuilt README.md, campaign home and', len(EVA_FOLDERS) + len(CAMPAIGN_FOLDERS), 'folder indexes')
